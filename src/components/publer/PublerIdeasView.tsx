import React, { useState } from 'react';
import { 
  Plus, 
  Search, 
  RefreshCw, 
  Layout, 
  MoreHorizontal, 
  Sparkles, 
  Info, 
  ArrowRight,
  Send,
  Trash2,
  CheckCircle2,
  Clock,
  Loader2
} from 'lucide-react';
import { geminiService } from '../../services/geminiService';

export interface IdeaCard {
  id: string;
  title: string;
  column: 'todo' | 'inprogress' | 'ready';
  assignee?: string;
  imageUrl?: string;
  notes?: string;
  createdAt: string;
}

const DEFAULT_IDEAS: IdeaCard[] = [
  {
    id: 'idea-1',
    title: 'Get a little help from AI while jotting down Draft Ideas. 🤖',
    column: 'todo',
    assignee: 'Unassigned',
    notes: 'Draft 5 hooks for the next product launch on X and Facebook.',
    createdAt: 'Today',
  },
  {
    id: 'idea-2',
    title: 'Never Miss a Spark of Social Media Genius Again! 💡',
    column: 'todo',
    assignee: 'Unassigned',
    notes: 'Record behind-the-scenes video for TikTok and Instagram Reels.',
    createdAt: 'Yesterday',
  },
  {
    id: 'idea-3',
    title: 'Halal Marriage & Community Spotlight Story',
    column: 'inprogress',
    assignee: 'Maryam',
    imageUrl: 'https://images.unsplash.com/photo-1522202176988-66273c2fd55f?w=600&auto=format&fit=crop&q=80',
    notes: 'Highlight community testimonials and Islamic family values.',
    createdAt: 'Oct 1',
  },
  {
    id: 'idea-4',
    title: 'Weekend Engagement Question: Your favorite wedding tradition?',
    column: 'ready',
    assignee: 'Unassigned',
    notes: 'Interactive poll for Facebook Group and WhatsApp Status.',
    createdAt: 'Oct 1',
  },
];

interface PublerIdeasViewProps {
  onOpenComposer: (date?: string, post?: any) => void;
}

export const PublerIdeasView: React.FC<PublerIdeasViewProps> = ({ onOpenComposer }) => {
  const [ideas, setIdeas] = useState<IdeaCard[]>(() => {
    try {
      const saved = localStorage.getItem('publer_ideas_v1');
      return saved ? JSON.parse(saved) : DEFAULT_IDEAS;
    } catch {
      return DEFAULT_IDEAS;
    }
  });

  const [searchQuery, setSearchQuery] = useState('');
  const [showAddModal, setShowAddModal] = useState(false);
  const [newTitle, setNewTitle] = useState('');
  const [newNotes, setNewNotes] = useState('');
  const [isGeneratingAi, setIsGeneratingAi] = useState(false);

  const saveIdeas = (updated: IdeaCard[]) => {
    setIdeas(updated);
    localStorage.setItem('publer_ideas_v1', JSON.stringify(updated));
  };

  const handleAddIdea = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newTitle.trim()) return;

    const newIdea: IdeaCard = {
      id: `idea-${Date.now()}`,
      title: newTitle.trim(),
      column: 'todo',
      assignee: 'Unassigned',
      notes: newNotes.trim() || undefined,
      createdAt: 'Just now',
    };

    saveIdeas([...ideas, newIdea]);
    setNewTitle('');
    setNewNotes('');
    setShowAddModal(false);
  };

  const handleGenerateAiIdeas = async () => {
    setIsGeneratingAi(true);
    try {
      const res = await geminiService.generatePost({
        topic: 'Halal Lifestyle, Marriage, and Community Engagement for Nigeria & global audience',
        tone: 'inspirational' as any,
        selectedPlatforms: ['twitter', 'facebook', 'instagram'],
      });

      const lines = (res.caption || '').split('\n').filter((l: string) => l.trim().length > 10).slice(0, 3);
      const fallbackIdeas = [
        'How to build consistent social presence while staying authentic',
        'Top questions our community asks about matrimonial vetting',
        'Behind the scenes of our verified Halal network'
      ];
      const sourceList = lines.length > 0 ? lines : fallbackIdeas;

      const generated: IdeaCard[] = sourceList.map((line: string, idx: number) => ({
        id: `idea-ai-${Date.now()}-${idx}`,
        title: line.replace(/^[\d.-]+\s*/, ''),
        column: 'todo',
        assignee: 'Unassigned',
        notes: 'Generated by Publer AI Assist',
        createdAt: 'Just now',
      }));

      saveIdeas([...generated, ...ideas]);
    } catch (e) {
      console.warn('AI Idea Generation error:', e);
    } finally {
      setIsGeneratingAi(false);
    }
  };

  const handleDeleteIdea = (id: string) => {
    saveIdeas(ideas.filter(i => i.id !== id));
  };

  const handleConvertToPost = (idea: IdeaCard) => {
    onOpenComposer(undefined, {
      id: `post-idea-${Date.now()}`,
      content: `${idea.title}\n\n${idea.notes || ''}`,
      platforms: ['twitter', 'facebook', 'whatsapp'],
      targetAccountIds: [],
      scheduledFor: new Date().toISOString(),
      status: 'draft',
      createdAt: new Date().toISOString(),
      author: 'Current User',
    });
  };

  const filteredIdeas = ideas.filter(i => 
    i.title.toLowerCase().includes(searchQuery.toLowerCase()) || 
    (i.notes && i.notes.toLowerCase().includes(searchQuery.toLowerCase()))
  );

  const todoList = filteredIdeas.filter(i => i.column === 'todo');
  const inProgressList = filteredIdeas.filter(i => i.column === 'inprogress');
  const readyList = filteredIdeas.filter(i => i.column === 'ready');

  return (
    <div className="p-4 sm:p-6 max-w-4xl mx-auto space-y-4 pb-24 animate-in fade-in duration-200">
      
      {/* Subheader Controls (Screenshot 2 Top) */}
      <div className="flex items-center justify-between gap-3">
        <button
          type="button"
          onClick={handleGenerateAiIdeas}
          disabled={isGeneratingAi}
          className="text-xs sm:text-sm font-semibold text-cyan-500 hover:text-cyan-600 flex items-center gap-1.5 cursor-pointer disabled:opacity-50"
        >
          {isGeneratingAi ? (
            <Loader2 className="w-4 h-4 animate-spin" />
          ) : (
            <Layout className="w-4 h-4" />
          )}
          <span>{isGeneratingAi ? 'Generating Ideas...' : 'View Customization'}</span>
        </button>

        <button
          type="button"
          onClick={() => setShowAddModal(true)}
          className="px-4 py-2 bg-cyan-500 hover:bg-cyan-600 text-white rounded-xl text-xs sm:text-sm font-bold shadow-xs transition-all cursor-pointer flex items-center gap-1 active:scale-98"
        >
          <Plus className="w-4 h-4" />
          <span>Add new</span>
        </button>
      </div>

      {/* Search & Refresh Row (Screenshot 2 Search Row) */}
      <div className="flex items-center gap-2">
        <button
          type="button"
          onClick={() => setSearchQuery('')}
          className="p-2.5 bg-white border border-slate-200 rounded-xl text-slate-500 hover:text-slate-800 cursor-pointer shadow-xs"
          title="Refresh ideas"
        >
          <RefreshCw className="w-4 h-4" />
        </button>

        <div className="relative flex-1">
          <Search className="w-4 h-4 text-slate-400 absolute left-3.5 top-1/2 -translate-y-1/2 pointer-events-none" />
          <input
            type="text"
            placeholder="Search here"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            className="w-full text-xs sm:text-sm pl-9 pr-3 py-2 bg-white border border-slate-200 rounded-xl placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-cyan-500/20 focus:border-cyan-500 shadow-xs"
          />
        </div>
      </div>

      {/* Kanban Board Columns (Screenshot 2 Body) */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4 pt-2">
        
        {/* Column 1: To Do */}
        <div className="space-y-3">
          <div className="flex items-center justify-between px-1">
            <span className="text-xs sm:text-sm font-extrabold text-slate-800 flex items-center gap-1.5">
              <span>💡 To Do ({todoList.length})</span>
            </span>
            <MoreHorizontal className="w-4 h-4 text-slate-400 cursor-pointer" />
          </div>

          <div className="space-y-2.5">
            {todoList.map((idea) => (
              <div
                key={idea.id}
                className="bg-white p-3.5 rounded-2xl border border-slate-200/80 shadow-xs hover:border-cyan-300 transition-all space-y-2 group"
              >
                <div className="flex items-center justify-between text-[11px] text-slate-400">
                  <div className="flex items-center gap-1.5">
                    <span className="w-3.5 h-3.5 rounded-full border border-dashed border-slate-300 inline-block" />
                    <span>{idea.assignee || 'Unassigned'}</span>
                  </div>
                  <Info className="w-3.5 h-3.5 text-cyan-400 shrink-0" />
                </div>

                <h4 className="text-xs sm:text-sm font-bold text-slate-900 leading-snug line-clamp-2">
                  {idea.title}
                </h4>

                {idea.notes && (
                  <p className="text-[11px] text-slate-500 line-clamp-2">
                    {idea.notes}
                  </p>
                )}

                <div className="flex items-center justify-between pt-1 border-t border-slate-100">
                  <span className="text-[10px] text-slate-400 font-mono">{idea.createdAt}</span>
                  <div className="flex items-center gap-1">
                    <button
                      type="button"
                      onClick={() => handleConvertToPost(idea)}
                      className="px-2 py-0.5 bg-cyan-50 hover:bg-cyan-100 text-cyan-700 rounded-md text-[10px] font-bold flex items-center gap-1 cursor-pointer transition-colors"
                    >
                      <Send className="w-2.5 h-2.5" />
                      <span>Create Post</span>
                    </button>
                    <button
                      type="button"
                      onClick={() => handleDeleteIdea(idea.id)}
                      className="p-1 text-slate-300 hover:text-rose-500 rounded"
                    >
                      <Trash2 className="w-3 h-3" />
                    </button>
                  </div>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Column 2: In Progress */}
        <div className="space-y-3">
          <div className="flex items-center justify-between px-1">
            <span className="text-xs sm:text-sm font-extrabold text-slate-800 flex items-center gap-1.5">
              <span>🚧 In Progress ({inProgressList.length})</span>
            </span>
            <MoreHorizontal className="w-4 h-4 text-slate-400 cursor-pointer" />
          </div>

          <div className="space-y-2.5">
            {inProgressList.map((idea) => (
              <div
                key={idea.id}
                className="bg-white p-3.5 rounded-2xl border border-slate-200/80 shadow-xs hover:border-cyan-300 transition-all space-y-2"
              >
                <div className="flex items-center justify-between text-[11px] text-slate-400">
                  <div className="flex items-center gap-1.5">
                    <span className="w-3.5 h-3.5 rounded-full border border-dashed border-slate-300 inline-block" />
                    <span>{idea.assignee || 'Unassigned'}</span>
                  </div>
                  <Info className="w-3.5 h-3.5 text-cyan-400 shrink-0" />
                </div>

                {idea.imageUrl && (
                  <img
                    src={idea.imageUrl}
                    alt={idea.title}
                    className="w-full h-24 object-cover rounded-xl border border-slate-100"
                  />
                )}

                <h4 className="text-xs sm:text-sm font-bold text-slate-900 leading-snug">
                  {idea.title}
                </h4>

                <div className="flex items-center justify-between pt-1 border-t border-slate-100">
                  <span className="text-[10px] text-slate-400 font-mono">{idea.createdAt}</span>
                  <button
                    type="button"
                    onClick={() => handleConvertToPost(idea)}
                    className="px-2 py-0.5 bg-cyan-50 hover:bg-cyan-100 text-cyan-700 rounded-md text-[10px] font-bold flex items-center gap-1 cursor-pointer"
                  >
                    <Send className="w-2.5 h-2.5" />
                    <span>Create Post</span>
                  </button>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Column 3: Ready to Post */}
        <div className="space-y-3">
          <div className="flex items-center justify-between px-1">
            <span className="text-xs sm:text-sm font-extrabold text-slate-800 flex items-center gap-1.5">
              <span>✅ Ready to Schedule ({readyList.length})</span>
            </span>
            <MoreHorizontal className="w-4 h-4 text-slate-400 cursor-pointer" />
          </div>

          <div className="space-y-2.5">
            {readyList.map((idea) => (
              <div
                key={idea.id}
                className="bg-white p-3.5 rounded-2xl border border-slate-200/80 shadow-xs hover:border-cyan-300 transition-all space-y-2"
              >
                <div className="flex items-center justify-between text-[11px] text-slate-400">
                  <div className="flex items-center gap-1.5">
                    <CheckCircle2 className="w-3.5 h-3.5 text-emerald-500" />
                    <span>{idea.assignee || 'Ready'}</span>
                  </div>
                  <Info className="w-3.5 h-3.5 text-cyan-400 shrink-0" />
                </div>

                <h4 className="text-xs sm:text-sm font-bold text-slate-900 leading-snug">
                  {idea.title}
                </h4>

                <div className="flex items-center justify-between pt-1 border-t border-slate-100">
                  <span className="text-[10px] text-slate-400 font-mono">{idea.createdAt}</span>
                  <button
                    type="button"
                    onClick={() => handleConvertToPost(idea)}
                    className="px-2.5 py-1 bg-cyan-500 hover:bg-cyan-600 text-white rounded-lg text-[10px] font-bold flex items-center gap-1 cursor-pointer shadow-xs"
                  >
                    <Send className="w-2.5 h-2.5" />
                    <span>Post Now</span>
                  </button>
                </div>
              </div>
            ))}
          </div>
        </div>

      </div>

      {/* Add Idea Modal */}
      {showAddModal && (
        <div className="fixed inset-0 z-50 bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-2xl shadow-2xl border border-slate-200 p-5 w-full max-w-sm space-y-4 animate-in zoom-in-95">
            <h3 className="text-sm font-bold text-slate-900">Add New Post Idea</h3>
            <form onSubmit={handleAddIdea} className="space-y-3">
              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">Idea Title</label>
                <input
                  type="text"
                  required
                  placeholder="e.g. 5 Halal Marriage Tips for Young Couples"
                  value={newTitle}
                  onChange={(e) => setNewTitle(e.target.value)}
                  className="w-full text-xs px-3 py-2 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-cyan-500"
                />
              </div>
              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">Notes / Key Points</label>
                <textarea
                  rows={3}
                  placeholder="Points to include in the draft..."
                  value={newNotes}
                  onChange={(e) => setNewNotes(e.target.value)}
                  className="w-full text-xs p-3 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-cyan-500"
                />
              </div>
              <div className="flex justify-end gap-2 pt-1">
                <button
                  type="button"
                  onClick={() => setShowAddModal(false)}
                  className="px-3 py-1.5 text-xs text-slate-600"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="px-4 py-1.5 bg-cyan-500 hover:bg-cyan-600 text-white rounded-xl text-xs font-bold shadow-xs cursor-pointer"
                >
                  Save Idea
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

    </div>
  );
};
